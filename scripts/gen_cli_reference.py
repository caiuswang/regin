"""Regenerate the "CLI reference" section of docs/setup.md from the live `regin` command tree.

    .venv/bin/python scripts/gen_cli_reference.py          # rewrite the section in place
    .venv/bin/python scripts/gen_cli_reference.py --check  # exit 1 if the section is stale
"""

from __future__ import annotations

import sys
from pathlib import Path

import click
import typer.main

ROOT = Path(__file__).resolve().parents[1]
SETUP_MD = ROOT / "docs" / "setup.md"
START = "<!-- cli-reference:start (generated by scripts/gen_cli_reference.py) -->"
END = "<!-- cli-reference:end -->"


def command_tree() -> click.Group:
    sys.path.insert(0, str(ROOT))
    from cli.app import app

    return typer.main.get_command(app)


def _summary(cmd: click.Command) -> str:
    # click's short help stops at the first period, which cuts "EXPERIMENTAL. Route …" and "e.g." mid-line.
    first = next(iter((cmd.short_help or cmd.help or "").strip().splitlines()), "")
    # `regin skills` interpolates the active provider's skills dir into its help; keep the doc machine-independent.
    from cli.commands.skills import _SKILLS_LABEL

    first = first.replace(_SKILLS_LABEL, "the active provider's skills directory")
    return first.replace("|", "\\|")


def _visible(group: click.Group) -> list[tuple[str, click.Command]]:
    return [(name, cmd) for name, cmd in group.commands.items() if not cmd.hidden]


def render(root: click.Group) -> str:
    commands = _visible(root)
    flat = [(n, c) for n, c in commands if not isinstance(c, click.Group)]
    groups = [(n, c) for n, c in commands if isinstance(c, click.Group)]
    lines = [
        START,
        "",
        "Run any command with `--help` for its arguments and flags.",
        "",
        "| Command | What it does |",
        "|---|---|",
        *(f"| `regin {name}` | {_summary(cmd)} |" for name, cmd in flat),
        "",
        "Command groups — `regin <group> <subcommand>`:",
        "",
        "| Group | What it covers | Subcommands |",
        "|---|---|---|",
    ]
    for name, group in groups:
        subs = " · ".join(f"`{sub}`" for sub, _ in _visible(group))
        lines.append(f"| `regin {name}` | {_summary(group)} | {subs} |")
    lines += ["", END]
    return "\n".join(lines)


def splice(doc: str, section: str) -> str:
    head, _, rest = doc.partition(START)
    _, _, tail = rest.partition(END)
    return head + section + tail


def main(argv: list[str]) -> int:
    doc = SETUP_MD.read_text(encoding="utf-8")
    if START not in doc or END not in doc:
        print(f"{SETUP_MD}: missing the cli-reference markers", file=sys.stderr)
        return 2
    updated = splice(doc, render(command_tree()))
    if "--check" in argv:
        if updated != doc:
            print("docs/setup.md CLI reference is stale — run scripts/gen_cli_reference.py", file=sys.stderr)
            return 1
        return 0
    SETUP_MD.write_text(updated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
